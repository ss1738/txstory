#!/usr/bin/env node
/**
 * Inventory of third-party packages from package-lock.json + installed metadata.
 *   node scripts/third-party.mjs > THIRD_PARTY_NOTICES.md
 * "Distributed" = code shipped in the built client bundle or the container's
 * production node_modules. License texts are copied from the installed packages.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const pkgs = Object.entries(lock.packages).filter(([p]) => p.startsWith('node_modules/'));
const meta = (p) => { try { return JSON.parse(readFileSync(join(p, 'package.json'), 'utf8')); } catch { return {}; } };
const licenseText = (p) => {
  const f = existsSync(p) ? readdirSync(p).find((x) => /^(licen[cs]e|copying)(\.|$)/i.test(x)) : null;
  return f ? readFileSync(join(p, f), 'utf8').trim() : null;
};
// Runtime: production dependencies (and their production dependencies).
const runtime = pkgs.filter(([, v]) => !v.dev);
const dev = pkgs.filter(([, v]) => v.dev);
const row = ([p, v]) => { const m = meta(p); return { name: p.replace(/^.*node_modules\//, ''), version: v.version, license: v.license ?? m.license ?? 'UNKNOWN' }; };
const L = [];
L.push('# Third-party notices', '');
L.push('Generated by `scripts/third-party.mjs` from `package-lock.json` and the installed packages. Regenerate after dependency changes.', '');
L.push('## Distributed with TxStory', '');
L.push('These packages are bundled into the built web client (`dist/client`) and/or installed in the container (`npm ci --omit=dev`). Their license texts follow.', '');
L.push('| Package | Version | License |', '|---|---|---|');
for (const r of runtime.map(row)) L.push(`| ${r.name} | ${r.version} | ${r.license} |`);
L.push('');
for (const [p] of runtime) {
  const r = row([p, lock.packages[p]]);
  const t = licenseText(p);
  L.push(`### ${r.name} ${r.version} (${r.license})`, '', t ? '```text\n' + t + '\n```' : '_No license file found in the installed package; see its repository._', '');
}
L.push('## Development tooling (not distributed)', '');
L.push('Used to build and test; not shipped in the client bundle or the container runtime.', '');
const byLicense = {};
for (const r of dev.map(row)) (byLicense[r.license] ??= []).push(`${r.name}@${r.version}`);
for (const [lic, names] of Object.entries(byLicense).sort((a, b) => b[1].length - a[1].length)) L.push(`- **${lic}** (${names.length}): ${names.join(', ')}`);
L.push('', '## External tools used by optional scripts (not bundled)', '');
L.push('- Foundry (`anvil`, `cast`, `forge`): used by `examples/devnet/scenario.ts` and `scripts/gen-abi-vectors.mjs` to generate test data. Not required to build, test or run TxStory.');
L.push('- Solidity compiler (via Foundry): compiles `examples/devnet/src/Demo.sol`.');
L.push('- Google Chrome / Chromium: used by the browser test suite.');
process.stdout.write(L.join('\n') + '\n');
